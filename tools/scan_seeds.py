"""Generate recomp_scan.toml: function seeds the finder cannot reach on its own.

1. Thumb functions referenced only through pointer tables (state/callback
   tables): an aligned odd word anywhere in the ROM that points into the code
   region at a PUSH {..., lr}.
2. ARM routines in the IWRAM image (ROM 0x087FA21C -> RAM 0x03003150, copied by
   crt0 with DMA3): word-aligned pointers into the image found in the code
   region's literal pools or in the image itself, whose target is an
   always-condition ARM instruction that follows a return/branch/literal.

Output is an overlay (no [program]); recomp.toml stays hand-written.
"""
import struct, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
rom = (root.parent / "Duke Nukem Advanced # GBA.GBA").read_bytes()
SHA1 = "f01522ee46f5aa821adbba0a97b1a745ff9059f5"
CODE_LO, CODE_HI = 0x080000C0, 0x080308D0
IW_RAM, IW_ROM, IW_SIZE = 0x03003150, 0x087FA21C, 0x411C
u16 = lambda a: struct.unpack_from("<H", rom, a - 0x08000000)[0]
u32 = lambda a: struct.unpack_from("<I", rom, a - 0x08000000)[0]
iw  = lambda a: u32(a - IW_RAM + IW_ROM)

thumb = {}
for off in range(0, len(rom) - 3, 4):
    v = struct.unpack_from("<I", rom, off)[0]
    if v & 1 and CODE_LO <= v < CODE_HI and (u16(v & ~1) & 0xFF00) == 0xB500:
        thumb.setdefault(v & ~1, 0x08000000 + off)

# 3. Return points of hand-built Thumb calls: "add lr, pc" then "bx rN" (the
#    long-call idiom: lr = this + 4 | 1). The callee returns to the
#    instruction after the bx, which netplay (no interpreter) needs as an entry.
ret_points = {}
for a in range(CODE_LO, CODE_HI - 4, 2):
    if u16(a) == 0x44FE and (u16(a + 2) & 0xFF87) == 0x4700:
        ret_points.setdefault(a + 4, a)

def arm_entry_ok(a):
    w = iw(a)
    if (w >> 28) != 0xE or (w & 0x0F000000) == 0x0F000000:   # always-cond, not SWI
        return False
    if a == IW_RAM: return True
    p = iw(a - 4)
    is_ret   = (p & 0x0FFFFFF0) == 0x012FFF10                      # bx rN
    is_pop   = (p & 0x0FFF8000) == 0x08BD8000 or (p & 0xFFFF0000) == 0xE8BD0000 and p & 0x8000
    is_b     = (p & 0xFF000000) == 0xEA000000                      # b
    is_movpc = (p & 0x0FFFF000) == 0x01A0F000                      # mov pc, rN
    is_data  = (p >> 28) != 0xE or (p >> 24) in (0x03, 0x08, 0x02, 0x04, 0x00)
    return is_ret or is_pop or is_b or is_movpc or is_data

arm = {}
srcs = [(a, u32(a)) for a in range(CODE_LO & ~3, CODE_HI, 4)]
srcs += [(IW_RAM + o, iw(IW_RAM + o)) for o in range(0, IW_SIZE & ~3, 4)]
for where, v in srcs:
    if IW_RAM <= v < IW_RAM + IW_SIZE and v % 4 == 0 and arm_entry_ok(v):
        arm.setdefault(v, where)

out = ['# AUTO-GENERATED by tools/scan_seeds.py — do not edit; rerun the script.',
       '[identity]', f'sha1 = "{SHA1}"', '']
for a, ref in sorted(thumb.items()):
    out += ['[[extra_func]]', f'addr = 0x{a:08X}', 'mode = "thumb"',
            f'note = "pointer-table target (word at 0x{ref:08X}), PUSH-LR prologue"', '']
for a, ref in sorted(ret_points.items()):
    if a in thumb: continue
    out += ['[[extra_func]]', f'addr = 0x{a:08X}', 'mode = "thumb"',
            f'note = "return point of the long call at 0x{ref:08X} (add lr, pc; bx)"', '']
for a, ref in sorted(arm.items()):
    out += ['[[extra_func]]', f'addr = 0x{a:08X}', 'mode = "arm"',
            f'note = "IWRAM image routine (pointer at 0x{ref:08X})"', '']
(root / "recomp_scan.toml").write_text("\n".join(out), encoding="utf-8")
print(f"thumb pointer-table seeds: {len(thumb)}   long-call return points: {len(ret_points)}"
      f"   IWRAM ARM seeds: {len(arm)}")
print("IWRAM seeds:", " ".join(f"{a:08X}" for a in sorted(arm)))

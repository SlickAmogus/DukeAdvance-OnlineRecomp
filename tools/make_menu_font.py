"""Writes src/menu_font.h: the bitmap font the PC menus are drawn with.

    python tools/make_menu_font.py

The glyphs are Pillow's built-in bitmap font (ImageFont.load_default_imagefont),
ASCII 0x20..0x7E, one byte per row (bit 7 = leftmost pixel) plus a width per
glyph. The menus add the colour, outline and shadow themselves.
"""
import pathlib
from PIL import Image, ImageDraw, ImageFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
font = ImageFont.load_default_imagefont()
H = 11
rows, widths = [], []
for c in range(0x20, 0x7F):
    ch = chr(c)
    w = max(1, int(font.getlength(ch)))
    img = Image.new("1", (16, 16), 0)
    ImageDraw.Draw(img).text((0, 0), ch, fill=1, font=font)
    glyph = []
    for y in range(H):
        bits = 0
        for x in range(8):
            if x < 16 and img.getpixel((x, y)):
                bits |= 0x80 >> x
        glyph.append(bits)
    rows.append(glyph)
    widths.append(min(w, 8))
out = ["// Generated by tools/make_menu_font.py from Pillow's built-in bitmap font.",
       "#pragma once", "#include <cstdint>", "",
       f"constexpr int kMenuFontHeight = {H};",
       "// ASCII 0x20..0x7E: one byte per row, bit 7 = leftmost pixel.",
       f"constexpr std::uint8_t kMenuFontRows[95][{H}] = {{"]
for c, g in zip(range(0x20, 0x7F), rows):
    out.append("    {" + ", ".join(f"0x{b:02X}" for b in g) + f"}},  // {chr(c)!r}")
out.append("};")
out.append("constexpr std::uint8_t kMenuFontWidth[95] = {")
out.append("    " + ", ".join(str(w) for w in widths))
out.append("};")
(ROOT / "src" / "menu_font.h").write_text("\n".join(out) + "\n")
# preview
prev = Image.new("RGB", (16 * 8 * 3, 6 * 12 * 3), (40, 0, 0))
for i, g in enumerate(rows):
    for y, b in enumerate(g):
        for x in range(8):
            if b & (0x80 >> x):
                for dy in range(3):
                    for dx in range(3):
                        prev.putpixel(((i % 16) * 24 + x * 3 + dx, (i // 16) * 36 + y * 3 + dy), (255, 80, 80))
prev.save(ROOT / "build" / "menu_font_preview.png")
print("widths", widths[:40])
